"""Build grammar/scribe.lark from grammar/scribe.lark.tmpl.

The language has two kinds of keyword:

HARD  reserved everywhere. A HARD word can never be a name. These are the words
      that start statements and clauses, the operator and comparison words, the
      argument labels, and the articles. Each one must be HARD because, if it
      were allowed as a name, a line could be read both as a statement and as a
      call (measured in experiment 3, see results/).
SOFT  every other word that appears in a fixed phrase ("restarts", "network",
      "queue", "version" ...). A SOFT word is a keyword only inside its own
      phrase and an ordinary name everywhere else, like Python's `match`.

QUANTITY is a number followed by a word that is not a keyword: `30 seconds`.
The lexer knows the fixed keyword list of the language, so this needs no
symbol table.
"""
import os
import re
import sys

HARD = set("""
to given produces fails expect ensure changes uses idempotent declassifies
deadline holds may
let be var starts set return fail try handle on failure if otherwise for each
increment decrement add subtract do
all any none then
labelled matching limited added only
from until through repeat while invariant decreases stop skip choose when hold
together pipeline trust assert
type choice define component system protocol schema migration example
property field model interface
is not and or implies mod of every there where result it some nothing at
less more than most least after before followed attenuated
with in into onto over using by as
a an the
""".split())


# Phrases the lexer reads as one token, so a parser that looks one token ahead
# sees both words at once. Each is written with its words separated by spaces;
# the text a reader sees is unchanged.
JOINED = [
    ("OR_ELSE", [",", "or", "else"]),
    ("COMMA_OR", [",", "or"]),
    ("FOR_EACH", ["for", "each"]),
    ("AT_ENTRY", ["at", "entry"]),
]


def joined_terminals():
    lines = []
    # earlier entries take priority, so `, or else` is tried before `, or`
    for rank, (name, parts) in enumerate(JOINED):
        pattern = ""
        for i, part in enumerate(parts):
            if part == ",":
                pattern += ","
            else:
                pattern += ("[ ]*" if i and parts[i - 1] == "," else "[ ]+" if i else "") + part
        lines.append(f"{name}.{9 - rank}: /{pattern}(?![A-Za-z0-9_])/")
    return "\n".join(lines) + "\n"


def keyword_list(hard, soft):
    """The keyword file the compiler embeds: one keyword per line, with its kind."""
    lines = ["# Generated by tools/build_grammar.py from grammar/scribe.lark.tmpl. Do not edit.",
             "# hard: reserved everywhere. soft: a keyword only inside its own phrase."]
    lines += [f"hard {w}" for w in sorted(hard)] + [f"soft {w}" for w in sorted(soft)]
    return "\n".join(lines) + "\n"


def build(tmpl_path, out_path, keywords_path=None):
    text = open(tmpl_path).read()
    # literal words used in the grammar, ignoring comments
    body = "\n".join(line.split("//")[0] for line in text.split("\n"))
    words = set(re.findall(r'"([A-Za-z_][A-Za-z0-9_]*)"', body))
    words |= {part for _, parts in JOINED for part in parts if part != ","}
    soft = sorted(words - HARD)
    missing_hard = sorted(HARD - words)
    # longest first, so no keyword matches as a prefix of another; ties by spelling,
    # so the build is the same on every run
    keywords = sorted(words | HARD, key=lambda w: (-len(w), w))
    lookahead = "|".join(keywords)
    name_rule = "name: NAME\n    | " + "\n    | ".join(f'"{w}"' for w in soft) + "\n"
    quantity = ("QUANTITY.4: /\\d+(\\.\\d+)?[ ]+(?!(" + lookahead +
                ")(?![A-Za-z0-9_]))[A-Za-z][A-Za-z0-9_]*/\n")
    out = text + "\n// ---- generated\n" + name_rule + quantity + joined_terminals()
    open(out_path, "w").write(out)
    if keywords_path:
        open(keywords_path, "w").write(keyword_list(HARD & words, soft))
    return sorted(HARD & words), soft, missing_hard


if __name__ == "__main__":
    out = sys.argv[2]
    hard, soft, missing = build(sys.argv[1], out, os.path.join(os.path.dirname(out), "keywords.txt"))
    print(f"hard keywords used: {len(hard)}")
    print(f"soft keywords: {len(soft)}")
    if missing:
        print("listed as HARD but unused:", missing)
